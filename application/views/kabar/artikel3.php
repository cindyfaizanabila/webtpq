            <h1>Menyambut Tahun Baru Hijriyah dengan Semangat Hijrah di TPQ Darul Furqon
            </h1>

            <div class="info-artikel">
                        <span>Ditulis oleh <strong>Mulawarman</strong></span> |
                        <span>Rilis: 5 Mei 2025</span>
            </div>
            <p>
            Tahun Baru Hijriyah bukan hanya pergantian kalender Islam, melainkan momentum untuk memperkuat semangat hijrah—berpindah dari hal yang buruk menuju kebaikan, dari gelap menuju cahaya iman. Di TPQ Darul Furqon, momen 1 Muharram 1447 H disambut dengan penuh makna oleh seluruh santri, ustadz-ustadzah, dan keluarga besar lembaga.
            </p>
            <p>
            Peringatan Tahun Baru Islam menjadi ajang refleksi dan pembelajaran. Kegiatan diawali dengan pembacaan doa akhir dan awal tahun yang dipimpin oleh para ustadz, diikuti dengan lantunan shalawat dan nasyid yang dibawakan oleh para santri. Dengan suara polos dan semangat yang membara, anak-anak mengekspresikan rasa cinta mereka terhadap Islam, seraya mengenang perjuangan Rasulullah SAW dan para sahabat dalam peristiwa hijrah dari Makkah ke Madinah.
            </p>
            <p>
            TPQ Darul Furqon juga mengemas peringatan ini dalam bentuk kegiatan edukatif dan menyenangkan, seperti lomba ceramah cilik bertema "Hijrahku Hari Ini", hafalan doa hijrah, hingga kegiatan menggambar kaligrafi bertuliskan “1 Muharram” dan “Hijrah Menuju Kebaikan”. Semua kegiatan ini bertujuan menanamkan makna hijrah dalam kehidupan anak-anak secara sederhana namun membekas.
            </p>
            <p>
            Selain itu, ustadz dan ustadzah memberikan tausiyah ringan tentang pentingnya hijrah dalam kehidupan sehari-hari. Hijrah bukan hanya berpindah tempat, tetapi juga berpindah sikap—misalnya, dari malas mengaji menjadi rajin, dari suka membantah menjadi patuh, dari suka marah menjadi sabar. Dengan bahasa yang mudah dipahami, para santri.
            </p>
            <p>
            Acara ditutup dengan doa bersama dan pembagian bingkisan sederhana untuk santri yang aktif dan berprestasi. Meskipun dilaksanakan dengan kesederhanaan, peringatan Tahun Baru Hijriyah di TPQ Darul Furqon tetap terasa penuh semangat, makna, dan kebersamaan.
            </p>
            <p>
            Semoga semangat hijrah senantiasa hidup di hati para santri TPQ Darul Furqon, menjadikan mereka pribadi yang lebih dekat dengan Allah, lebih cinta kepada Al-Qur’an, dan lebih semangat meneladani akhlak Rasulullah SAW. Selamat Tahun Baru Islam 1447 H—semoga menjadi awal yang baik untuk hijrah kita semua menuju ridha-Nya.
            </p>

