            <h1>Merayakan Cinta kepada Rasulullah: Maulid Nabi di TPQ Darul Furqon
            </h1>

            <div class="info-artikel">
                        <span>Ditulis oleh <strong>Kudungga</strong></span> |
                        <span>Rilis: 5 Mei 2025</span>
            </div>
            <p>
            Peringatan Maulid Nabi Muhammad SAW selalu menjadi momen yang penuh makna dan kehangatan di TPQ Darul Furqon. Setiap tahunnya, seluruh keluarga besar TPQ—dari santri, ustadz-ustadzah, wali santri, hingga masyarakat sekitar—turut ambil bagian dalam merayakan kelahiran manusia agung, panutan seluruh umat Islam, Rasulullah Muhammad SAW.
            </p>
            <p>
            Acara Maulid Nabi bukan sekadar peringatan seremonial, melainkan wujud nyata kecintaan kepada Rasulullah. Kegiatan diawali dengan pembacaan ayat suci Al-Qur’an dan shalawat bersama yang menggema dengan penuh kekhusyukan. Santri-santri tampil membacakan maulid, menyampaikan puisi, dan juga ceramah kecil tentang keteladanan akhlak Rasulullah, yang mereka pelajari selama di TPQ. Meskipun masih kecil, semangat mereka untuk mencintai Nabi begitu besar dan tulus, memancarkan harapan besar untuk masa depan generasi Qur’ani yang mencintai agamanya.
            </p>
            <p>
            Selain itu, acara juga diisi dengan kisah-kisah tentang kehidupan Rasulullah SAW—bagaimana beliau bersikap lembut, jujur, amanah, dan penuh kasih sayang terhadap semua makhluk. Cerita-cerita itu disampaikan dengan bahasa yang mudah dipahami oleh anak-anak, agar mereka bisa meneladani sifat-sifat Nabi dalam kehidupan sehari-hari, baik di rumah maupun di lingkungan sekolah.
            </p>
            <p>
            Tak ketinggalan, suasana semakin meriah dengan pembagian hadiah dan bingkisan sederhana bagi para santri yang tampil atau memenangkan lomba-lomba Islami yang diselenggarakan menjelang Maulid, seperti lomba adzan, hafalan doa, serta mewarnai gambar bertema Nabi Muhammad SAW. Semua kegiatan ini menjadi bagian dari pendidikan karakter yang disampaikan dengan cara yang menyenangkan dan menyentuh hati.
            </p>
            <p>
            Melalui peringatan Maulid Nabi ini, TPQ Darul Furqon ingin menanamkan nilai-nilai kecintaan kepada Rasulullah sejak dini. Karena dari cinta itulah, akan tumbuh semangat untuk meneladani dan mengamalkan sunnah beliau dalam kehidupan sehari-hari. Semoga setiap anak didik kami tumbuh menjadi pribadi yang jujur, penyayang, dan membawa cahaya Islam dalam setiap langkahnya—sebagaimana Rasulullah adalah cahaya bagi seluruh alam
            </p>

